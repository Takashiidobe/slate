#!/usr/bin/env python3

import argparse
import concurrent.futures
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TABLES = ROOT / "src/target/x86_isa_tables.rs"
GCC_SPELLINGS = {"x87": "80387"}
GCC_MACROS = {"Usermsr": ["__USER_MSR__"]}
LATE_IMPLIED = {"Sse42": {"Popcnt", "Crc32"}, "Sse": {"Mmx"}}


def table_body(source, function):
    start = source.index(f"fn {function}(self)")
    return source[start:source.index("\n    }\n", start)]


def defined_macros(gcc, args):
    result = subprocess.run(
        [gcc, *args, "-dM", "-E", "-x", "c", "/dev/null"], capture_output=True, text=True
    )
    if result.returncode:
        return None
    return set(re.findall(r"#define (\w+)", result.stdout))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--gcc", default="gcc")
    parser.add_argument("--output", type=Path, default=ROOT / "src/target/x86_isa_gcc_tables.rs")
    args = parser.parse_args()

    source = TABLES.read_text()
    spellings = dict(re.findall(r'Self::(\w+) => "([^"]+)"', table_body(source, "spelling")))
    macros = {
        name: re.findall(r'"(\w+)"', listed)
        for name, listed in re.findall(r"Self::(\w+) => &\[([^\]]*)\]", table_body(source, "macros"))
    }
    variants = list(spellings)
    macros.update(GCC_MACROS)

    def features(defined):
        return {name for name in variants if any(m in defined for m in macros[name])}

    bases = {
        ("-m32", "-march=i386"): features(defined_macros(args.gcc, ["-m32", "-march=i386"])),
        ("-march=x86-64",): features(defined_macros(args.gcc, ["-march=x86-64"])),
    }

    def flag(name, prefix="-m"):
        return f"{prefix}{GCC_SPELLINGS.get(spellings[name], spellings[name])}"

    def enabled(name):
        for base, present in bases.items():
            defined = defined_macros(args.gcc, [*base, flag(name)])
            if defined is not None:
                closure = features(defined) - present - {name}
                for trigger, late in LATE_IMPLIED.items():
                    if trigger in closure | {name}:
                        closure -= late
                return closure
        return None

    with concurrent.futures.ThreadPoolExecutor(32) as pool:
        enables = dict(zip(variants, pool.map(enabled, variants)))
        accepted = [name for name in variants if enables[name] is not None]
        rich = ["-march=x86-64-v4", *map(flag, accepted)]
        all_on = features(defined_macros(args.gcc, rich))
        if all_on != {name for name in accepted if macros[name]}:
            raise SystemExit(f"enabling every flag misses {sorted(set(accepted) - all_on)}")
        disables = dict(zip(accepted, pool.map(
            lambda name: all_on - features(defined_macros(args.gcc, [*rich, flag(name, "-mno-")])) - {name},
            accepted,
        )))
    version = subprocess.run([args.gcc, "--version"], capture_output=True, text=True,
                             check=True).stdout.splitlines()[0]

    def bits(names):
        return f"0x{sum(1 << variants.index(n) for n in names):032x}"

    lines = [
        f"// generated by tools/generate_x86_isa_gcc.py from {version}; do not edit",
        "",
        "use super::x86_isa_tables::X86Feature;",
        "",
        "impl X86Feature {",
        "    pub(super) fn gcc_enables(self) -> Option<u128> {",
        "        match self {",
        *[
            f"            Self::{name} => {'None' if implied is None else f'Some({bits(implied)})'},"
            for name, implied in enables.items()
        ],
        "        }",
        "    }",
        "",
        "    pub(super) fn gcc_disables(self) -> u128 {",
        "        match self {",
        *[f"            Self::{name} => {bits(disables.get(name, set()))}," for name in variants],
        "        }",
        "    }",
        "",
        "    pub(super) fn gcc_macros(self) -> &'static [&'static str] {",
        "        match self {",
        *[
            f"            Self::{name} => &[{', '.join(f'\"{m}\"' for m in macros[name])}],"
            for name in variants
        ],
        "        }",
        "    }",
        "}",
    ]
    args.output.write_text("\n".join(lines) + "\n")
    rejected = [spellings[name] for name, implied in enables.items() if implied is None]
    print(f"{len(variants)} features; rejected by gcc: {', '.join(rejected)}")


if __name__ == "__main__":
    main()
